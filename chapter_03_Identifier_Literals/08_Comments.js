// ============================================
// JAVASCRIPT COMMENT EXAMPLES
// ============================================

// 1. SINGLE-LINE COMMENT
// Use // to write a comment on a single line.
// Anything after // is ignored by JavaScript.
let x = 10; // This is an inline comment
console.log(x);

// 2. MULTI-LINE COMMENT
/*
  This is a multi-line comment.
  It can span several lines.
  Useful for longer explanations or disabling a block of code.
*/
let y = 20;
console.log(y);

// 3. COMMENTING OUT CODE
// You can disable code without deleting it.
// console.log("This line is commented out and won\'t run");
let result = x + y;
console.log(result);

// 4. INLINE COMMENT
let total = 100; // total amount
console.log(total);

// 5. DOCUMENTING CODE
// Comments are also used to explain purpose and logic:
function add(a, b) {
  // add two numbers and return the result
  return a + b;
}
console.log(add(5, 7));
